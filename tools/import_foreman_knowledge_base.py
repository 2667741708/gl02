def import_foreman_knowledge() -> dict[str, Any]:
    """将工长实操经验知识库导入 PostgreSQL bf_assistant.rag_* 表。"""

    full_text = "\n\n".join(
        f"## {e['title']}\n\n{e['content']}" for e in KNOWLEDGE_ENTRIES
    )
    ts = utc_now()
    task_scope_json = json.dumps(TASK_SCOPES, ensure_ascii=False)

    with raw_pg_connect() as conn:
        ensure_rag_schema(conn)

        # 先删除旧版（如果存在），实现幂等导入
        conn.execute("DELETE FROM rag_chunk WHERE doc_id = %s", (DOC_ID,))
        conn.execute("DELETE FROM rag_document WHERE doc_id = %s", (DOC_ID,))

        # 插入文档记录
        conn.execute(
            """
            INSERT INTO rag_document(
                doc_id, title, source_file, knowledge_category, task_scope_json,
                version, authority_level, full_text, content_hash, created_at, updated_at
            ) VALUES(%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            """,
            (
                DOC_ID,
                DOC_TITLE,
                SOURCE_FILE,
                KNOWLEDGE_CATEGORY,
                task_scope_json,
                VERSION,
                AUTHORITY_LEVEL,
                full_text,
                content_hash(full_text),
                ts,
                ts,
            ),
        )

        # 插入每条知识chunk
        for entry in KNOWLEDGE_ENTRIES:
            enriched = (
                f"【文档标题】{DOC_TITLE}\n"
                f"【知识类别】{KNOWLEDGE_CATEGORY}\n"
                f"【适用任务】炉况诊断、工艺问答、参数优化、运行报告、案例分析\n"
                f"【章节】{entry['title']}\n"
                f"【关键词】{'、'.join(entry['keywords'])}\n"
                f"【关联现象】{'、'.join(entry['phenomenon']) if entry['phenomenon'] else '无特定现象'}\n"
                f"【关联变量（可查看时间趋势曲线）】{'、'.join(entry['entities'])}\n"
                f"【正文片段】\n{entry['content']}"
            )

            conn.execute(
                """
                INSERT INTO rag_chunk(
                    chunk_id, doc_id, parent_chunk_id, title, content, enriched_content,
                    summary, keywords_json, entities_json, phenomenon_json, parameter_names_json,
                    chunk_type, token_count, source_file, knowledge_category, task_scope_json,
                    authority_level, source_priority, content_hash, created_at
                ) VALUES(%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    entry["chunk_id"],
                    DOC_ID,
                    f"{DOC_ID}_parent",
                    entry["title"],
                    entry["content"],
                    enriched,
                    entry["content"][:120],
                    json.dumps(entry["keywords"], ensure_ascii=False),
                    json.dumps(entry["entities"], ensure_ascii=False),
                    json.dumps(entry["phenomenon"], ensure_ascii=False),
                    json.dumps(entry["entities"], ensure_ascii=False),
                    entry["chunk_type"],
                    len(entry["content"]),
                    SOURCE_FILE,
                    KNOWLEDGE_CATEGORY,
                    task_scope_json,
                    AUTHORITY_LEVEL,
                    source_priority(KNOWLEDGE_CATEGORY),
                    content_hash(entry["content"]),
                    ts,
                ),
            )

        conn.commit()

    return {
        "ok": True,
        "doc_id": DOC_ID,
        "doc_title": DOC_TITLE,
        "chunks": len(KNOWLEDGE_ENTRIES),
        "storage": "postgresql",
        "schema": schema_name(),
        "knowledge_category": KNOWLEDGE_CATEGORY,
    }


